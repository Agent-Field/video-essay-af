"""Calm sentence captions as an ASS file, rendered by libass.

An essay is not a reel.  Reels burst one word at a time to hold a scrolling
thumb; a 16:9 video essay is watched deliberately, so the caption sits still
at the bottom of the frame for the whole sentence and simply follows the
narration.  That means one Dialogue event per sentence, timed to the
sample-accurate span the TTS module measured — long sentences are broken
into consecutive chunks so nothing ever grows past two lines.

We emit the ASS text by hand rather than through pysubs2: the file is a
couple of dozen lines of a well-specified format, and hand-writing keeps the
module dependency-free and the escaping explicit.
"""

from __future__ import annotations

import re
from pathlib import Path

from reasoners.models import Sentence, SentenceTiming

# ───── Look ──────────────────────────────────────────────────────────

# ASS colours are &HAABBGGRR — alpha first, then BGR.  00 alpha = opaque.
_WHITE = "&H00FFFFFF"
_BLACK = "&H00000000"
_SHADOW = "&H78000000"  # ~47% transparent black — a soft drop, not a box

_OUTLINE_PX = 3
_SHADOW_PX = 2

# Reference geometry the pixel constants below were chosen against.
_REF_HEIGHT = 1080
_MARGIN_V_AT_1080 = 72

_MAX_LINES = 2

# Fonts we can actually rely on, best first.  The family name is what goes
# into the ASS style; the path is what a caller may need to hand to a
# container/fontconfig so libass can find it.
_FONT_CANDIDATES: list[tuple[str, str]] = [
    ("/usr/share/fonts/truetype/montserrat/Montserrat-Bold.ttf", "Montserrat"),
    ("/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", "DejaVu Sans"),
    ("/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf", "Liberation Sans"),
    ("/usr/share/fonts/truetype/liberation2/LiberationSans-Bold.ttf", "Liberation Sans"),
]

_TAG_RE = re.compile(r"\[[^\]]*\]")


# ───── Helpers ───────────────────────────────────────────────────────


def find_font() -> tuple[str, str]:
    """First installed caption font → ``(font_path, family_name)``."""
    for path, family in _FONT_CANDIDATES:
        if Path(path).exists():
            return path, family
    raise RuntimeError(
        "find_font: no caption font installed — expected one of "
        + ", ".join(p for p, _ in _FONT_CANDIDATES)
    )


def _ass_time(seconds: float) -> str:
    """Seconds → ``H:MM:SS.cc``, the only time format ASS accepts."""
    total_cs = int(round(max(0.0, seconds) * 100))
    hours, rest = divmod(total_cs, 360000)
    minutes, rest = divmod(rest, 6000)
    secs, cs = divmod(rest, 100)
    return f"{hours:d}:{minutes:02d}:{secs:02d}.{cs:02d}"


def _clean(text: str) -> str:
    """Spoken text only: no ``[stage directions]``, no stray whitespace."""
    return " ".join(_TAG_RE.sub(" ", text or "").split())


def _escape(text: str) -> str:
    """Neutralise anything libass would read as markup.

    ``{`` opens an override block, so an unescaped brace in the narration
    could swallow the rest of the caption (or inject a tag).  Braces are
    vanishingly rare in spoken prose, so mapping them to parentheses is
    both safe and visually honest.
    """
    return (
        text.replace("\\", "/")
        .replace("{", "(")
        .replace("}", ")")
        .replace("\r", " ")
        .replace("\n", " ")
    )


def _wrap(text: str, max_chars: int) -> list[str]:
    """Greedy word wrap to lines of at most ``max_chars`` characters."""
    words = text.split()
    if not words:
        return []
    lines: list[str] = []
    current = words[0]
    for word in words[1:]:
        if len(current) + 1 + len(word) <= max_chars:
            current = f"{current} {word}"
        else:
            lines.append(current)
            current = word
    lines.append(current)
    return lines


def _chunk(text: str, max_chars: int) -> list[list[str]]:
    """Split a caption into consecutive groups of at most ``_MAX_LINES`` lines.

    Anything that fits in two lines stays one chunk; longer sentences turn
    into several chunks that play back to back, always breaking at word
    boundaries.
    """
    lines = _wrap(text, max_chars)
    if not lines:
        return []
    return [lines[i : i + _MAX_LINES] for i in range(0, len(lines), _MAX_LINES)]


def _script_info(width: int, height: int) -> list[str]:
    return [
        "[Script Info]",
        "; Sentence captions for a 16:9 video essay — generated by video-essay-af",
        "ScriptType: v4.00+",
        f"PlayResX: {width}",
        f"PlayResY: {height}",
        "WrapStyle: 0",
        "ScaledBorderAndShadow: yes",
        "YCbCr Matrix: TV.709",
        "",
    ]


def _styles(font_name: str, font_size: int, width: int, height: int) -> list[str]:
    scale = height / _REF_HEIGHT
    margin_v = max(8, int(round(_MARGIN_V_AT_1080 * scale)))
    margin_h = max(16, int(round(width * 0.06)))
    outline = max(1, int(round(_OUTLINE_PX * scale)))
    shadow = max(0, int(round(_SHADOW_PX * scale)))
    return [
        "[V4+ Styles]",
        (
            "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, "
            "OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, "
            "ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, "
            "Alignment, MarginL, MarginR, MarginV, Encoding"
        ),
        (
            f"Style: Caption,{font_name},{font_size},{_WHITE},{_WHITE},"
            f"{_BLACK},{_SHADOW},-1,0,0,0,100,100,0,0,1,{outline},{shadow},"
            f"2,{margin_h},{margin_h},{margin_v},1"
        ),
        "",
    ]


# ───── Public API ────────────────────────────────────────────────────


def write_captions_ass(
    sentences: list[Sentence],
    timings: list[SentenceTiming],
    out_path: Path,
    *,
    width: int = 1920,
    height: int = 1080,
    font_name: str = "Montserrat",
    font_size: int = 46,
    max_chars_per_line: int = 46,
) -> Path:
    """Write bottom-centre sentence captions to ``out_path`` and return it.

    ``timings`` is matched to ``sentences`` by ``index``; a sentence with no
    timing is skipped rather than guessed at.  A sentence too long for two
    lines becomes several consecutive captions whose share of the sentence's
    span is proportional to their character count, so the text keeps pace
    with the voice without any extra measurement.
    """
    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)

    by_index = {t.index: t for t in timings}
    lines: list[str] = []
    lines += _script_info(width, height)
    lines += _styles(font_name, font_size, width, height)
    lines += [
        "[Events]",
        (
            "Format: Layer, Start, End, Style, Name, MarginL, MarginR, "
            "MarginV, Effect, Text"
        ),
    ]

    for sentence in sentences:
        timing = by_index.get(sentence.index)
        if timing is None:
            continue
        span = max(0.0, timing.end_s - timing.start_s)
        if span <= 0.0:
            continue

        chunks = _chunk(_clean(sentence.text), max_chars_per_line)
        if not chunks:
            continue

        weights = [max(1, sum(len(line) for line in chunk)) for chunk in chunks]
        total = float(sum(weights))
        cursor = timing.start_s
        for i, (chunk, weight) in enumerate(zip(chunks, weights, strict=True)):
            end = timing.end_s if i == len(chunks) - 1 else cursor + span * weight / total
            text = "\\N".join(_escape(line) for line in chunk)
            lines.append(
                f"Dialogue: 0,{_ass_time(cursor)},{_ass_time(end)},Caption,,0,0,0,,{text}"
            )
            cursor = end

    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return out_path


__all__ = ["find_font", "write_captions_ass"]
